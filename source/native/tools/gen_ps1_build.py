"""Writes build_ps1.inc (sourced by build.sh): the car build of PCSX ReARMed (the PS1 emulator), from the compile
commands its own makefile gives for platform=qnx (ARM dynarec; GPU selected by make overrides), turned into qcc commands.

  cd third_party/pcsx_rearmed && make -f Makefile.libretro platform=qnx HAVE_PHYSICAL_CDROM=0 CFLAGS_OPT=-O2 CC=QCC BUILTIN_GPU=peops HAVE_NEON_ASM=1 DYNAREC=ari64 -Bn \\
      | grep '^QCC' > cmds.txt
  python tools/gen_ps1_build.py cmds.txt > build_ps1.inc        (run from native/)"""
import shlex
import sys

lines = ["# Generated by tools/gen_ps1_build.py from PCSX ReARMed's makefile (platform=qnx). Sourced by build.sh with",
         "# $ps1_dir set; objects go to out/ps1.",
         "mkdir -p out/ps1"]
for raw in open(sys.argv[1], encoding="utf-8"):
    toks = shlex.split(raw.strip())
    assert toks[0] == "QCC"
    if "-c" not in toks:
        continue   # the makefile's own link step (a .so); ours links ps1-qnx in build.sh
    out, src, args = None, None, []
    i = 1
    while i < len(toks):
        t = toks[i]
        if t == "-o":
            out = toks[i + 1]
            i += 2
            continue
        if t == "-c":
            src = toks[i + 1]
            i += 2
            continue
        if t in ("-MMD", "-MP", "-Wall") or t.startswith("-Wno-") or t.startswith("-DGIT_VERSION"):
            i += 1
            continue
        if t.startswith("-I"):
            args.append('-I"$ps1_dir/%s"' % t[2:])
        elif t.startswith("-m") or (t.startswith("-f") and t != "-fPIC"):
            args.append("-Wc," + t)
        else:
            args.append(shlex.quote(t))
        i += 1
    assert out and src, raw
    obj = "out/ps1/" + out.replace("/", "_")
    # gcc 4.4 defines none of the byte-order macros; undefined, a "== __ORDER_BIG_ENDIAN__" test is true (0 == 0)
    # and the code takes its big-endian path. The car is little-endian ARM. .S files also want the NEON macro.
    std = "-D__ARM_NEON__ -Wa,-mcpu=cortex-a9 -Wa,-mfpu=neon " if src.endswith(".S") else "-Wc,-std=gnu99 "
    std += "-D__ORDER_LITTLE_ENDIAN__=1234 -D__ORDER_BIG_ENDIAN__=4321 -D__ORDER_PDP_ENDIAN__=3412 -D__BYTE_ORDER__=1234 "
    lines.append('qcc -V4.4.2,gcc_ntoarmv7le %s-w -I"$ps1_compat" -DGIT_VERSION=\'"7b0e8f8"\' %s -c "$ps1_dir/%s" -o %s' % (std, " ".join(args), src, obj))
print("\n".join(lines))
